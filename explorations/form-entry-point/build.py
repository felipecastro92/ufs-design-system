#!/usr/bin/env python3
"""Build form-entry-point/index.html: a DS clone of the live AEM article
/africa-middle-east/morocco/en/chef-inspiration/burger-route/burger-trends/free-burger-recipe-book-for-you

Shell = handover/template-inspiration.html (real header, drawer, footer,
bottom nav, controls bar, JS), with <main id="inspiration-main"> swapped
for _main.html. Component CSS is lifted from the handover specs so it
stays in sync. Run from anywhere: python3 build.py"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
HO = os.path.join(HERE, '../../handover')
rd = lambda p: open(p, encoding='utf-8').read()

# ── 1. Component CSS from the specs (doc-only .pv-* rules dropped) ──
def component_css(spec, prefix):
    s = rd(os.path.join(HO, spec))
    css = ''.join(re.findall(r'<style[^>]*>(.*?)</style>', s, re.S))
    out = []
    for m in re.finditer(r'(@media[^{]+\{(?:[^{}]*\{[^}]*\})*\s*\})|([^{}@]+\{[^}]*\})', css):
        t = m.group(0).strip()
        if prefix not in t:
            continue
        if m.group(1):  # strip pv-* rules inside @media
            t = re.sub(r'[^{}]*\.pv-[^{}]*\{[^}]*\}', '', t)
        elif '.pv-' in t.split('{')[0]:
            continue
        t = re.sub(r'/\*.*?\*/', '', t, flags=re.S).strip()
        out.append(t)
    return f'/* ── from handover/{spec} ── */\n' + '\n'.join(out) + '\n'

comp = '/* GENERATED by build.py, do not edit. */\n'
for spec, prefix in [('utility-bar-spec.html', 'ufs-utility-bar'),
                     ('text-block-spec.html', 'ufs-text-block'),
                     ('promo-banner-spec.html', 'ufs-promo-banner')]:
    comp += component_css(spec, prefix)
open(os.path.join(HERE, 'components.css'), 'w', encoding='utf-8').write(comp)

# ── 1b. Download form CSS from forms-examples.html (side panel, fi-*
#        fields, reg-* business/consent/success, av success icon), plus
#        the keyframes those rules use. Asset paths → handover/. ──
def form_css():
    s = rd(os.path.join(HO, 'forms-examples.html'))
    css = re.sub(r'/\*.*?\*/', '', re.search(r'<style>(.*?)</style>', s, re.S).group(1), flags=re.S)
    pat = re.compile(r'\.(signin-(backdrop|panel|close|form-fields|usp)|fi-|reg-|av-check-badge|av--xl|av-circle|av-icon-mail)')
    rules, frames = [], {}
    for m in re.finditer(r'(@(?:media|supports)[^{]+\{(?:[^{}]*\{[^}]*\})*\s*\})|(@keyframes\s+([\w-]+)[^{]*\{(?:[^{}]*\{[^}]*\})*\s*\})|([^{}@]+\{[^}]*\})', css):
        t = m.group(0).strip()
        if m.group(1):
            inner = [r.strip() for r in re.findall(r'[^{}]+\{[^}]*\}', t[t.index('{') + 1:]) if pat.search(r.split('{')[0])]
            if inner:
                rules.append(t[:t.index('{')].strip() + ' {\n  ' + '\n  '.join(inner) + '\n}')
        elif m.group(2):
            frames[m.group(3)] = t
        elif pat.search(t.split('{')[0]):
            rules.append(t)
    body = '\n'.join(rules)
    body += '\n' + '\n'.join(v for k, v in frames.items() if re.search(r'\b' + re.escape(k) + r'\b', body))
    body = re.sub(r"url\((['\"]?)(icons|images)/", r"url(\1../../handover/\2/", body)
    return '/* GENERATED by build.py from handover/forms-examples.html, do not edit. */\n' + body + '\n'

open(os.path.join(HERE, 'form-panel.css'), 'w', encoding='utf-8').write(form_css())

# ── 2. Shell from template-inspiration ──
html = rd(os.path.join(HO, 'template-inspiration.html'))

# Asset paths → handover/
html = html.replace('href="tokens.css"', 'href="../../handover/tokens.css"')
html = re.sub(r'(src|href)="(icons|images|fonts|video)/', r'\1="../../handover/\2/', html)
html = re.sub(r"url\((['\"]?)(icons|images|fonts)/", r"url(\1../../handover/\2/", html)
html = re.sub(r'href="((?:template-|full-page-preview|index)[^"#]*\.html)', r'href="../../handover/\1', html)
html = html.replace('<option value="full-page-preview-v0.2.html"', '<option value="../../handover/full-page-preview-v0.2.html"')

# Title + page CSS
html = re.sub(r'<title>.*?</title>', '<title>Free Download: 13 ultimate burger recipes — Form entry point — UFS</title>', html, count=1, flags=re.S)
html = html.replace('</head>', '  <link rel="stylesheet" href="components.css" />\n  <link rel="stylesheet" href="form-panel.css" />\n  <link rel="stylesheet" href="form-entry-point.css" />\n</head>', 1)

# The template's document click handler expects #catalog-sort, which lives
# in the main swapped out below; guard it or every click throws.
_old = "if (sort.classList.contains('is-open') && !sort.contains(e.target))"
assert html.count(_old) == 1, 'catalog-sort click guard not found'
html = html.replace(_old, "if (sort && sort.classList.contains('is-open') && !sort.contains(e.target))")

# Download form panel + its logic, last in <body> (after the page script,
# which defines the global S the form reads for signed-in state)
assert html.count('</body>') == 1
html = html.replace('</body>', rd(os.path.join(HERE, '_form.html')) + '  <script src="form-panel.js"></script>\n</body>')

# Controls bar: hide the "Page" group (it switches to other templates' mains).
# Hidden rather than removed: applyState() still toggles its buttons by id.
html, n = re.subn(r'<div class="ctrl-group">(\s*<span class="ctrl-label">Page</span>.*?</div>\s*</div>)\s*<div class="ctrl-sep"></div>',
                  r'<div class="ctrl-group" hidden>\1', html, count=1, flags=re.S)
assert n == 1, 'Page control group not found'

# ── 3. Main ──
start = html.index('<main id="inspiration-main">')
end = html.index('</main>', start) + len('</main>')
old_main = html[start:end]

bc = old_main[old_main.index('<nav class="ufs-breadcrumb"'):]
bc = bc[:bc.index('</nav>') + 6]
sep = re.search(r'<li class="ufs-breadcrumb__sep".*?</li>', bc, re.S).group(0)
crumb = lambda t: f'<li class="ufs-breadcrumb__item"><a href="#" class="ufs-breadcrumb__link">{t}</a></li>'
bc = bc.replace(
    '<li class="ufs-breadcrumb__item is-current"><span class="ufs-breadcrumb__current" aria-current="page">Inspiration</span></li>',
    crumb('Chef Inspiration') + sep + crumb('Big on Burgers') + sep +
    '<li class="ufs-breadcrumb__item is-current"><span class="ufs-breadcrumb__current" aria-current="page">Burger Trends</span></li>')

main = rd(os.path.join(HERE, '_main.html')).replace('<!--BREADCRUMB-->', bc)
html = html[:start] + '<main id="inspiration-main">\n' + main + '  </main>' + html[end:]

open(os.path.join(HERE, 'index.html'), 'w', encoding='utf-8').write(html)
print('built index.html', len(html) // 1024, 'KB; components.css', len(comp) // 1024, 'KB')
